#!/bin/sh
# Regenerates src/vectors.h: SHA-256 digest of a fixed message and ECDSA P-256
# signatures (ASN.1 DER, as MCUboot's mbedtls/PSA backends expect) over it,
# made with each TEST P-256 key. TEST ONLY. Run from this directory.
set -e
KEYS=../../app/dmc/sysbuild/test-keys/p256
WORK=$(mktemp -d "$PWD/.vectors.XXXXXX")
printf 'mcuboot multi-key test vector\n' > "$WORK/msg.bin"
for k in a b; do
  openssl dgst -sha256 -sign "$KEYS/test-key-$k-p256.pem" \
    -out "$WORK/sig_$k.der" "$WORK/msg.bin"
done
{
  echo "/* Generated by gen_vectors.sh. TEST ONLY. */"
  echo "#include <stdint.h>"
  printf 'static const uint8_t vec_digest[32] = {'
  openssl dgst -sha256 -binary "$WORK/msg.bin" | od -An -tx1 | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g' | tr -d '\n'
  echo "};"
  for k in a b; do
    printf 'static const uint8_t vec_sig_%s[] = {' "$k"
    od -An -tx1 -v "$WORK/sig_$k.der" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g' | tr -d '\n'
    echo "};"
  done
} > src/vectors.h
rm -rf "$WORK"
echo "wrote src/vectors.h"
