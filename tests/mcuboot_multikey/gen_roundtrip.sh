#!/bin/sh
# Simulates the external-signer flow we expect from KMS/HSM, then writes the
# signed image as a C array for the ztest (src/roundtrip_image.h).
#
#   1. imgtool sign --vector-to-sign digest   (export the digest to sign)
#   2. openssl pkeyutl -sign                  (stand-in for the KMS/HSM call)
#   3. base64 the raw signature               (--fix-sig expects base64)
#   4. imgtool sign --fix-sig --fix-sig-pubkey (inject signature + key)
#   5. imgtool verify                          (check the result)
#
# TEST ONLY: uses a local P-256 test key. Run from this directory.
set -e
PY=${PYTHON:-../../../.venv/bin/python3}
IMGTOOL=../../../bootloader/mcuboot/scripts/imgtool.py
KEYS=../../app/dmc/sysbuild/test-keys/p256
KEY=$KEYS/test-key-b-p256.pem
PUB=$KEYS/test-key-b-p256.pub.pem
ARGS="--header-size 0x200 --pad-header --align 8 --version 1.0.0 --slot-size 0x80000"
WORK=$(mktemp -d "$PWD/.roundtrip.XXXXXX")

# Deterministic 4 KiB payload, so the output is reproducible.
$PY -c 'import sys; sys.stdout.buffer.write(bytes(i & 0xff for i in range(4096)))' > "$WORK/payload.bin"

# 1. Export the digest imgtool would sign.
$PY $IMGTOOL sign --key "$KEY" $ARGS --vector-to-sign digest "$WORK/payload.bin" "$WORK/digest.bin" >/dev/null

# 2. External signer: sign the digest with the key (KMS/HSM stand-in).
openssl pkeyutl -sign -inkey "$KEY" -in "$WORK/digest.bin" -out "$WORK/sig.der"

# 3. --fix-sig expects base64.
base64 -w0 "$WORK/sig.der" > "$WORK/sig.b64"

# 4. Inject the signature and the public key it belongs to.
$PY $IMGTOOL sign --fix-sig "$WORK/sig.b64" --fix-sig-pubkey "$PUB" $ARGS \
    "$WORK/payload.bin" "$WORK/signed.bin" >/dev/null

# 5. Check the result with imgtool before the ztest relies on it.
$PY $IMGTOOL verify --key "$PUB" "$WORK/signed.bin" >/dev/null

# Emit the signed image as a C array.
$PY - "$WORK/signed.bin" > src/roundtrip_image.h <<'EOF'
import sys
data = open(sys.argv[1], 'rb').read()
print("/* Generated by gen_roundtrip.sh. TEST ONLY. */")
print("#include <stdint.h>")
print("#include <stddef.h>")
print("static const uint8_t roundtrip_image[] = {")
for i in range(0, len(data), 12):
    print("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
print("};")
print("static const size_t roundtrip_image_len = sizeof(roundtrip_image);")
EOF

rm -rf "$WORK"
echo "wrote src/roundtrip_image.h"
